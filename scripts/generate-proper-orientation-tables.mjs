import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const repositoryRoot = resolve(dirname(scriptPath), "..");

const LEGACY_UPRIGHT_ROWS = Object.freeze([
  Object.freeze({
    id: "upright-yaw-0",
    matrix: Object.freeze([1, 0, 0, 0, 1, 0, 0, 0, 1]),
  }),
  Object.freeze({
    id: "upright-yaw-90",
    matrix: Object.freeze([0, 0, 1, 0, 1, 0, -1, 0, 0]),
  }),
  Object.freeze({
    id: "upright-yaw-180",
    matrix: Object.freeze([-1, 0, 0, 0, 1, 0, 0, 0, -1]),
  }),
  Object.freeze({
    id: "upright-yaw-270",
    matrix: Object.freeze([0, 0, -1, 0, 1, 0, 1, 0, 0]),
  }),
]);

const PERMUTATIONS = Object.freeze([
  Object.freeze([0, 1, 2]),
  Object.freeze([0, 2, 1]),
  Object.freeze([1, 0, 2]),
  Object.freeze([1, 2, 0]),
  Object.freeze([2, 0, 1]),
  Object.freeze([2, 1, 0]),
]);

function determinant(matrix) {
  return (
    matrix[0] * (matrix[4] * matrix[8] - matrix[5] * matrix[7]) -
    matrix[1] * (matrix[3] * matrix[8] - matrix[5] * matrix[6]) +
    matrix[2] * (matrix[3] * matrix[7] - matrix[4] * matrix[6])
  );
}

function matrixCode(matrix) {
  return matrix.map((entry) => (entry === -1 ? "n" : entry === 0 ? "0" : "p")).join("");
}

export function generateProperOrientationRows() {
  const rows = [];
  for (const permutation of PERMUTATIONS) {
    for (const firstSign of [-1, 1]) {
      for (const secondSign of [-1, 1]) {
        for (const thirdSign of [-1, 1]) {
          const matrix = Array(9).fill(0);
          matrix[permutation[0]] = firstSign;
          matrix[3 + permutation[1]] = secondSign;
          matrix[6 + permutation[2]] = thirdSign;
          if (determinant(matrix) !== 1) continue;
          rows.push(
            Object.freeze({
              id: `proper-m-${matrixCode(matrix)}`,
              matrix: Object.freeze(matrix),
            }),
          );
        }
      }
    }
  }

  const byMatrix = new Map(rows.map((row) => [row.matrix.join(","), row]));
  const legacyMatrices = new Set();
  for (const legacy of LEGACY_UPRIGHT_ROWS) {
    const generated = byMatrix.get(legacy.matrix.join(","));
    if (generated === undefined) {
      throw new Error(`Generator did not reproduce legacy orientation ${legacy.id}.`);
    }
    legacyMatrices.add(legacy.matrix.join(","));
  }
  if (rows.length !== 24 || byMatrix.size !== 24) {
    throw new Error(
      `Expected 24 unique determinant+1 signed-permutation matrices; generated ${rows.length} rows and ${byMatrix.size} unique matrices.`,
    );
  }

  const remainder = rows
    .filter(({ matrix }) => !legacyMatrices.has(matrix.join(",")))
    .sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));
  return Object.freeze([...LEGACY_UPRIGHT_ROWS, ...remainder]);
}

function typescriptBytes(rows) {
  const remainder = rows.slice(LEGACY_UPRIGHT_ROWS.length);
  const emittedRows = remainder
    .map(
      ({ id, matrix }) =>
        `    Object.freeze({\n      id: ${JSON.stringify(id)},\n      matrix: Object.freeze([${matrix.join(", ")}] as const),\n    }),`,
    )
    .join("\n");
  return `// Generated by scripts/generate-proper-orientation-tables.mjs. Do not edit.\nimport type { ProperOrientation } from "./types.ts";\n\n/** The 20 non-upright members; constants.ts prepends the four legacy upright rows. */\nexport const GENERATED_NON_UPRIGHT_PROPER_ORIENTATIONS: readonly ProperOrientation[] =\n  Object.freeze([\n${emittedRows}\n  ]);\n`;
}

function pythonBytes(rows) {
  const emittedRows = rows
    .map(({ id, matrix }) => `    (${JSON.stringify(id)}, (${matrix.join(", ")})),`)
    .join("\n");
  return `"""Generated by generate-proper-orientation-tables.mjs. Do not edit."""\n\nPROPER_ORIENTATION_ROWS: tuple[tuple[str, tuple[int, ...]], ...] = (\n${emittedRows}\n)\n\nPROPER_ORIENTATIONS: dict[str, tuple[int, ...]] = dict(PROPER_ORIENTATION_ROWS)\n`;
}

export function generatedProperOrientationFiles() {
  const rows = generateProperOrientationRows();
  return Object.freeze([
    Object.freeze({
      path: resolve(repositoryRoot, "packages/catalog/src/proper-orientations.generated.ts"),
      bytes: typescriptBytes(rows),
    }),
    Object.freeze({
      path: resolve(repositoryRoot, "scripts/proper_orientations_generated.py"),
      bytes: pythonBytes(rows),
    }),
  ]);
}

async function run() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("Usage: node scripts/generate-proper-orientation-tables.mjs [--check]");
  }
  const check = args[0] === "--check";
  const drifted = [];
  for (const output of generatedProperOrientationFiles()) {
    if (check) {
      const actual = await readFile(output.path, "utf8").catch(() => undefined);
      if (actual !== output.bytes) drifted.push(relative(repositoryRoot, output.path));
    } else {
      await writeFile(output.path, output.bytes, "utf8");
    }
  }
  if (drifted.length > 0) {
    throw new Error(
      `Generated proper-orientation tables are stale: ${drifted.join(", ")}. Run node scripts/generate-proper-orientation-tables.mjs.`,
    );
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === scriptPath) {
  await run();
}
