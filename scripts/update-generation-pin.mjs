// Regenerates the pinned digest of the deterministic maker run.
//
// The pin catches an accidental change to the deterministic path. It also moves
// every time catalog truth moves, because the run embeds the document's truth
// snapshot — and hand-copying a sha256 for that is both tedious and the easiest
// possible way to commit a wrong one. This writes it, and says which of the two
// causes it just recorded so a real behavioural change cannot slip past as
// routine catalog churn.
//
//   node scripts/update-generation-pin.mjs            write the pin
//   node scripts/update-generation-pin.mjs --check    fail if it is stale

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

import { canonicalDigest } from "@lego-studio/brick-kernel";
// By path rather than by package name: the pinned run is a fixture for one
// test, not something the browser bundle should be able to reach.
import { runDeterministicMakerPopulation } from "../packages/generation/src/population.ts";
import { liveCatalogTruth, pinnedRunInput } from "../packages/generation/src/run-pin.ts";
import {
  RUN_PIN_PATH,
  describeStaleRunPin,
  describeTextDifference,
  movedRunPinValues,
  nameSome,
} from "./generated-file-staleness.mjs";

const outputPath = fileURLToPath(new URL(`../${RUN_PIN_PATH}`, import.meta.url));
const checkOnly = process.argv.includes("--check");

const catalog = liveCatalogTruth();
const populationDigest = canonicalDigest(runDeterministicMakerPopulation(pinnedRunInput()));

const previous = await readFile(outputPath, "utf8").catch((error) => {
  if (error?.code === "ENOENT") return null;
  throw error;
});
// The staleness test is the whole formatted bytes below. These three are what a
// stale verdict has to be reported against, because they are what a reader acts
// on and everything else in the file is a comment or a line ending.
const produced = {
  catalogVersion: catalog.version,
  catalogTruthHash: catalog.hash,
  populationDigest,
};
const moved = movedRunPinValues(previous, produced);

const expected = await format(
  `// Generated by \`npm run pin:generate\`. Do not edit by hand.
//
// The digest of the one deterministic maker run this repository pins, and the
// catalog truth it was taken against. See packages/generation/src/run-pin.ts
// for why both are recorded.
import type { RunPin } from "./run-pin.ts";

export const DETERMINISTIC_RUN_PIN: RunPin = {
  catalogVersion: ${JSON.stringify(catalog.version)},
  catalogTruthHash: ${JSON.stringify(catalog.hash)},
  populationDigest: ${JSON.stringify(populationDigest)},
};
`,
  // The repository's own Prettier settings, or the generated file fails the
  // format gate that every other file passes.
  { ...(await resolveConfig(outputPath)), parser: "typescript" },
);

if (previous === expected) {
  console.log(`Deterministic run pin is current: ${populationDigest} (${catalog.version})`);
  process.exit(0);
}

if (checkOnly) {
  console.error(describeStaleRunPin(previous, expected, produced));
  process.exitCode = 1;
} else {
  await writeFile(outputPath, expected, "utf8");
  console.log(`Wrote ${populationDigest} to ${RUN_PIN_PATH}`);
  if (previous === null) {
    console.log(`  First write, against catalog truth ${catalog.version} ${catalog.hash}.`);
  } else if (moved.length === 0) {
    console.log(
      `  No pinned value moved: still ${catalog.version} ${catalog.hash} and ${populationDigest}. Only the file bytes changed — ${describeTextDifference(previous, expected)}.`,
    );
  } else if (!moved.includes("populationDigest")) {
    console.log(
      `  ${nameSome(moved)} moved; the digest did not, and is still ${populationDigest}.`,
    );
  } else if (moved.includes("catalogTruthHash")) {
    console.log(
      `  Catalog truth moved to ${catalog.version} ${catalog.hash}, which is what moved the digest. Expected for a catalog change.`,
    );
  } else {
    console.log(
      `  Catalog truth did NOT move (${catalog.version} ${catalog.hash}). The deterministic path itself changed — say what changed and why in the commit message, because nothing else will.`,
    );
  }
}
